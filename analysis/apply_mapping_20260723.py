# -*- coding: utf-8 -*-
"""2026-07-23 사용자 확정 수익자 매핑 반영.

- 한국밸류자산운용 → 한투밸류자산운용 통일
- 모펀드 매핑을 클래스로 이관: 08M60(→08M61/62), 08Q12(→08Q13/14) 삭제
- 신규 14건 추가 (가중치 포함)
"""
import pandas as pd

P = r'C:\Users\USER\Cowork\2026-07-23_수탁고-자동화\data\수익자.csv'
ben = pd.read_csv(P, dtype=str).fillna('')

# 1) 명칭 통일
for c in ('수익자1', '수익자2', '수익자3'):
    ben[c] = ben[c].replace('한국밸류자산운용', '한투밸류자산운용')

# 2) 모펀드 매핑 삭제 (클래스로 이관)
before = len(ben)
ben = ben[~ben['열1'].isin(['08M60', '08Q12'])]
print(f'삭제: {before - len(ben)}행 (08M60, 08Q12)')

# 3) 신규 추가 (열1, 수익자1, 수익자2, 수익자3, 부가설명, w1, w2, w3)
NEW = [
    ('06W41', 'NH은행(퇴직)', '', '', '', '', '', ''),
    ('06W42', '신한은행(퇴직)', '', '', '', '', '', ''),
    ('06W57', 'KB은행(퇴직)', '', '', '', '', '', ''),
    ('08M61', '건강보험', '', '', '뉴에이스7호 1종', '', '', ''),
    ('08M62', '한투밸류자산운용', '', '', '뉴에이스7호 2종', '', '', ''),
    ('08M65', '건설근로자공제회', '', '', '', '', '', ''),
    ('08N57', '건강보험', '', '', '뉴에이스8호 1종', '', '', ''),
    ('08N58', '한국투자저축은행', '', '', '뉴에이스8호 2종', '', '', ''),
    ('08P26', '국민은행', '', '', '', '', '', ''),
    ('08P39', '연기금풀(미래)', '', '', '', '', '', ''),
    ('08P55', '노동부(고용보험)', '', '', '', '', '', ''),
    ('08Q13', '신한은행', '카카오뱅크', '', '뉴에이스10호 1종 500/500', '500', '500', ''),
    ('08Q14', '카카오뱅크', '', '', '뉴에이스10호 2종', '', '', ''),
    ('08Q58', '삼성카드', '한국투자저축은행', '', '300/1', '300', '1', ''),
]
dupe = [r[0] for r in NEW if r[0] in set(ben['열1'])]
assert not dupe, f'중복 코드: {dupe}'
add = pd.DataFrame(NEW, columns=['열1', '수익자1', '수익자2', '수익자3', '부가설명',
                                 '수익자1수탁고', '수익자2수탁고', '수익자3수탁고'])
add['2024YE수탁고'] = ''
ben = pd.concat([ben, add], ignore_index=True)
ben.to_csv(P, index=False, encoding='utf-8-sig')
print(f'추가: {len(NEW)}행 → 총 {len(ben)}행')
print('한국밸류 잔존:', (ben[['수익자1', '수익자2', '수익자3']] == '한국밸류자산운용').any().any())
